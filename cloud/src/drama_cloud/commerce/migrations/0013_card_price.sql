-- 0013 卡密批次售价（审查批次 C，总方案第 6 条第 2 项）。
--
-- `card_batches` 补一列**售价**：运营生成一批卡时记下「这批卡当时定价多少」，
-- 事后对账、盘点才有依据。**只做记录**：卡密兑换改的是使用权，不是积分，
-- 这个值不参与任何扣费与兑换逻辑（不要让「改售价」变成一种改账本的途径）。
--
-- 可空：历史批次和没定价的批次都是 NULL，不代表「免费」，只是「没记」。
-- 单位是分：钱一律用整数存，界面层再换算成元。
-- 已执行的迁移不能再改；新改动写成新的编号文件。

ALTER TABLE card_batches
    ADD COLUMN price_fen integer CHECK (price_fen IS NULL OR price_fen >= 0);
